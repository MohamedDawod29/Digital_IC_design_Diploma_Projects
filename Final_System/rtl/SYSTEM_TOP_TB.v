`timescale 1us/100fs
module SYSTEM_TOP_TB;

	//TB signals
	
	reg REF_CLK,UART_CLK;
	reg RST;
	reg RX_IN;
	wire TX_OUT,Stop_Error,Parity_Error;
	
	//parameters 
	
	localparam UART_CLK_P = 0.2712673611, REF_CLK_P = 0.02;

		
	//clock generator
	
	
	always #(REF_CLK_P/2)   REF_CLK = ~REF_CLK;
	
	
	always #(UART_CLK_P/2)   UART_CLK = ~UART_CLK;
	
	//inistantiation
	
	SYSTEM_TOP DUT
	(
	.REF_CLK(REF_CLK),
	.UART_CLK(UART_CLK),
	.RST(RST),
	.RX_IN(RX_IN),
	.TX_OUT(TX_OUT),
	.Stop_Error(Stop_Error),
	.Parity_Error(Parity_Error)
	);
	
	
	//initial block and test cases
	
	initial 
	begin
		$dumpfile ("SYSTEM_TOP_TB.vcd");
		$dumpvars;
		
		initialization;
		reset;

		#(4*UART_CLK_P*32);

		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////////////// CONFIG [EVEN PARITY] [PRESCALE 32] ////////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	   
	   
		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////////////// Register File Write command (3 frames) ////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		
		//Frame0 ----->   Command                     //Frame1 ----->   Address             		//Frame2 ----->   Data 
		Frame (8'hAA);                    			  Frame (8'h05);                    			Frame (8'hA3);


		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////////////// Register File Read command (2 frames) /////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		//Frame0 ----->   Command    		          //Frame1 ----->   Address              		
		Frame (8'hBB);                    				Frame (8'h05);                        
		

		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////////// ALU Operation command with operand (4 frames) /////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		//Frame0 ----->   Command    		//Frame1 ----->   Op_A              		//Frame2 ----->   Op_B               	//Frame3 ----->   FUNC
		Frame (8'hCC);          			Frame (8'h03);                  			Frame (8'h05);		        			Frame (8'h00);
		 
 
		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////////// ALU Operation command with No operand (2 frames) //////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		//Frame0 ----->   Command                       //Frame1 ----->   FUNC
		Frame (8'hDD);                    				  Frame (8'h0C);

		#(UART_CLK_P*5000)                    //delay between the two different configurations

		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////// CONFIG [ODD PARITY] [PRESCALE 32] /////////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
	   
	     /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		////////////////////////////////////////////////////////// CHANGING CONFIG //////////////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
   
	    // Frame0 ----->   Command                     //Frame1 ----->   Address             		//Frame2 ----->   Data 
		Frame (8'hAA);                    				 Frame (8'h02);                   			Frame (8'h83);
	   
		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////// Register File Write command (3 frames) ////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		
		// Frame0 ----->   Command                     //Frame1 ----->   Address             		//Frame2 ----->   Data 
		Frame (8'hAA);                      			Frame (8'h06);                   			 Frame (8'hB5);


		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////////// Register File Read command (2 frames) /////////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		// Frame0 ----->   Command    		          //Frame1 ----->   Address              		
		Frame (8'hBB);                     				Frame (8'h06);                        
		

		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////// ALU Operation command with operand (4 frames) /////////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		// Frame0 ----->   Command    		//Frame1 ----->   Op_A              		//Frame2 ----->   Op_B             //Frame3 ----->   FUNC
		Frame (8'hCC);           			Frame (8'h09);                   			Frame (8'h07);		   				Frame (8'h00);
	 
		 
		 /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
		///////////////////////////////////////// ALU Operation command with No operand (2 frames) //////////////////////////////////////////////
	   /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

		// Frame0 ----->   Command                       //Frame1 ----->   FUNC
		Frame (8'hDD);                           		Frame (8'h01);

		
	#(UART_CLK_P*1000)
		
		$stop;
		
	end
	
	
	//initialization task
	
	task initialization;
		begin
			REF_CLK = 1'b0;
			UART_CLK = 1'b0;
			RST = 1'b1;
	        RX_IN = 1'b1;
		end
	endtask
	
	//reset task
	
	task reset;
		begin
			#(UART_CLK_P*32)
			RST = 1'b0;
			#(UART_CLK_P*32)
			RST = 1'b1;
			#(UART_CLK_P*32);
		end
	endtask
	
	// Frames even sending task
	
    task Frame;
        input [0:7] data;                          
        integer i;
        begin
            // Start bit doesn't change
            RX_IN = 1'b0;
            #(UART_CLK_P*32);

            // Data bits
            for (i = 0; i < 8 ; i = i + 1)
			begin
                RX_IN = data[i];
                #(UART_CLK_P*32);
            end
            
			if (DUT.B4.UART_CONFIG[1])             //if it equal 1 then odd parity else even parity
				RX_IN = ~^data;
			else
				RX_IN = ^data;
				
			#(UART_CLK_P*32);
            // Stop bit doesn't change
            RX_IN = 1'b1;
            #(UART_CLK_P*32);
        end
    endtask
	
	

endmodule
